def _find_source_image(image_dir: Path, serial: str, source_idx: int) -> Path:
    for name in (f"{source_idx:04d}.jpg", f"{source_idx:08d}.jpg", f"{source_idx:04d}.png"):
        p = image_dir / serial / name
        if p.exists():
            return p
    raise FileNotFoundError(f"source image missing: {image_dir / serial}/####{source_idx:04d}.jpg")


def _link_or_copy(src: Path, dst: Path, mode: str) -> str:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists():
        dst.unlink()
    if mode == "copy":
        shutil.copy2(src, dst)
        return "copy"
    if mode == "symlink":
        os.symlink(src, dst)
        return "symlink"
    try:
        os.link(src, dst)
        return "hardlink"
    except OSError:
        shutil.copy2(src, dst)
        return "copy_fallback"


def prepare_images_and_masks(out: Path, image_dir: Path, mask_root: Path,
                             cal: Dict[str, Any], mc: MotionContract,
                             link_mode: str) -> Dict[str, Any]:
    """Copy/link the original frames and the existing MJJ SAM2 masks.

    Mask source contract (verified in work/mjj/refine_body_surface.py:22):
        work/mjj/reconstruction/diagnosis/surface/masks/<serial>/<source_idx:04d>.png
    where <source_idx> is int(motion['source_frames'][t]), not the contiguous
    output pose_idx.  Missing masks are a hard error; no background-threshold
    fallback is generated in this round.
    """
    stats = {"images": 0, "masks": 0, "link_modes": {}, "mask_root": str(mask_root),
             "mask_sources": [], "warnings": []}
    for t in range(mc.T):
        src_idx = int(mc.source_frames[t])
        for ci, serial in enumerate(cal["cams"]):
            src_img = _find_source_image(image_dir, serial, src_idx)
            dst_img = _safe_under(out / "images" / f"cam{ci:02d}" / f"{t:08d}.jpg", out)
            mode = _link_or_copy(src_img, dst_img, link_mode)
            stats["link_modes"][mode] = stats["link_modes"].get(mode, 0) + 1
            stats["images"] += 1

            src_mask = mask_root / serial / f"{src_idx:04d}.png"
            if not src_mask.exists():
                raise FileNotFoundError(
                    f"existing MJJ SAM2 mask missing: {src_mask} "
                    f"(camera {serial}, source frame {src_idx}, output pose {t}). "
                    "No provisional mask is generated."
                )
            m = read_image(str(src_mask), cv.IMREAD_GRAYSCALE)
            if m is None:
                raise RuntimeError(f"cannot read existing mask {src_mask}")
            ref = read_image(str(src_img), cv.IMREAD_GRAYSCALE)
            if ref is None:
                raise RuntimeError(f"cannot read image for mask sizing {src_img}")
            if m.shape != ref.shape:
                raise ValueError(
                    f"mask size {m.shape} != image size {ref.shape} for {src_mask}; "
                    "refusing to resize masks and silently change the silhouette"
                )
            if m.max() <= 1:
                m = (m * 255).astype(np.uint8)
            m = np.where(m > 128, 255, 0).astype(np.uint8)
            dst_mask = _safe_under(out / "masks" / f"cam{ci:02d}" / f"{t:08d}.jpg", out)
            dst_mask.parent.mkdir(parents=True, exist_ok=True)
            ok = write_image(str(dst_mask), m, [cv.IMWRITE_JPEG_QUALITY, 100])
            if not ok:
                raise RuntimeError(f"mask write failed: {dst_mask}")
            stats["masks"] += 1
            if len(stats["mask_sources"]) < 8:
                stats["mask_sources"].append({
                    "cam": serial, "pose_idx": t, "source_frame": src_idx,
                    "source": str(src_mask),
                })
    return stats


