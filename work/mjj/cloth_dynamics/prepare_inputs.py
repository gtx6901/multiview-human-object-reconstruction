def main() -> int:
    ap = argparse.ArgumentParser(description="Prepare MJJ001 for AnimatableGaussians (CPU only).")
    ap.add_argument("--motion", default=str(DEFAULT_MOTION))
    ap.add_argument("--avatar", default=str(DEFAULT_AVATAR))
    ap.add_argument("--calibration", default=str(DEFAULT_CAL))
    ap.add_argument("--acceptance", default=str(DEFAULT_ACCEPTANCE))
    ap.add_argument("--assets", default=str(DEFAULT_ASSETS))
    ap.add_argument("--image-dir", default=None)
    ap.add_argument("--mask-root", default=str(DEFAULT_MASK_ROOT),
                    help="existing MJJ SAM2 masks, <root>/<serial>/<source_idx:04d>.png")
    ap.add_argument("--mask-mode", choices=["existing"], default="existing",
                    help="compatibility flag; only existing SAM2 masks are accepted")
    ap.add_argument("--output", default=str(DEFAULT_OUT))
    ap.add_argument("--smplx-dir", default=None)
    ap.add_argument("--template-ply", default=None)
    ap.add_argument("--template-scale", type=float, default=1.0)
    ap.add_argument("--map-size", type=int, default=1024)
    ap.add_argument("--max-frames", type=int, default=None,
                    help="smoke segment: use first N motion frames (default all 99)")
    ap.add_argument("--link-mode", choices=["hardlink", "copy", "symlink"], default="hardlink")
    ap.add_argument("--author-root", default=str(HERE / "author"),
                    help="author shallow clone root containing smplx/ and dataset/")
    ap.add_argument("--no-maps", action="store_true", help="layout-only smoke test")
    ap.add_argument("--no-qa", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--verify-only", action="store_true")
    a = ap.parse_args()

    out = Path(a.output).resolve()
    motion = Path(a.motion).resolve()
    cal_path = Path(a.calibration).resolve()
    assets = Path(a.assets).resolve()
    mask_root = Path(a.mask_root).resolve()
    image_dir = Path(a.image_dir).resolve() if a.image_dir else assets / "dynamic"

    if a.verify_only:
        mc = extract_motion(motion) if motion.exists() else None
        rep = verify_dataset(out, mc=mc, require_maps=not a.no_maps)
        print(json.dumps({"ok": rep["ok"], "errors": rep["errors"][:12],
                          "warnings": rep["warnings"][:8]}, indent=2))
        return 0 if rep["ok"] else 1

    mc = extract_motion(motion)
    if a.max_frames is not None:
        n = int(a.max_frames)
        if not 1 <= n <= mc.T:
            raise ValueError(f"--max-frames {n} outside 1..{mc.T}")
        mc = MotionContract(
            path=mc.path, T=n, root=mc.root[:n], body=mc.body[:n],
            transl_model=mc.transl_model[:n], betas=mc.betas, jaw=mc.jaw[:n],
            expr=mc.expr[:n], lh=mc.lh[:n], rh=mc.rh[:n], scale=mc.scale,
            fps=mc.fps, expr_dim=mc.expr_dim, source_frames=mc.source_frames[:n],
            key_report=mc.key_report, warnings=mc.warnings + [f"SMOKE: truncated to first {n} frames"],
        )
    cal = load_calibration(cal_path, Path(a.acceptance).resolve(), mc.scale)
    avatar = audit_avatar(Path(a.avatar).resolve())
    gauge = projection_gauge_check(cal, mc.scale, mc.transl_model)

    # Image sizes from the first real frame of each camera.
    sizes: List[List[int]] = []
    for serial in cal["cams"]:
        p = _find_source_image(image_dir, serial, int(mc.source_frames[0]))
        im = read_image(str(p), cv.IMREAD_COLOR)
        if im is None:
            raise RuntimeError(f"cannot read {p}")
        sizes.append([int(im.shape[1]), int(im.shape[0])])

    plan = {
        "output": str(out), "motion": str(motion), "avatar": str(Path(a.avatar).resolve()),
        "calibration": str(cal_path), "assets": str(assets), "image_dir": str(image_dir),
        "mask_root": str(mask_root),
        "T": mc.T, "fps": mc.fps, "scale": mc.scale,
        "source_frames_first_last": [int(mc.source_frames[0]), int(mc.source_frames[-1])],
        "cameras": cal["cams"], "image_sizes": sizes,
        "projection_gauge_max_px": gauge["max_px"],
        "avatar_load_error": avatar.get("load_error"),
        "smplx_dir": str(resolve_smplx_dir(a.smplx_dir)) if not a.no_maps else None,
        "author_root": str(Path(a.author_root).resolve()) if Path(a.author_root).exists() else None,
    }
    print(json.dumps(plan, indent=2)[:8000])
    if a.dry_run:
        src0 = int(mc.source_frames[0])
        missing_masks = [str(mask_root / serial / f"{src0:04d}.png")
                         for serial in cal["cams"]
                         if not (mask_root / serial / f"{src0:04d}.png").exists()]
        if missing_masks:
            print(json.dumps({"missing_masks_first_frame": missing_masks,
                              "mask_root": str(mask_root)}, indent=2), file=sys.stderr)
            return 2
        if gauge["max_px"] > 1e-2:
            print(f"WARNING: gauge projection max {gauge['max_px']} px", file=sys.stderr)
        if avatar.get("load_error"):
            print(f"WARNING: avatar audit failed: {avatar['load_error']}", file=sys.stderr)
        return 0

    out.mkdir(parents=True, exist_ok=True)
    if not image_dir.exists():
        raise FileNotFoundError(image_dir)
    mask_stats = prepare_images_and_masks(out, image_dir, mask_root, cal, mc, a.link_mode)
    write_calibration_json(out, cal, sizes)
    write_smpl_params(out, mc)
    write_dataset_meta(out, mc, cal, avatar, sizes, mask_stats, gauge, None)
    write_camera_contract(out, cal, gauge)

    maps_report = None
    if not a.no_maps:
        maps_report = build_template_and_maps(
            out, motion, resolve_smplx_dir(a.smplx_dir),
            template_ply=a.template_ply, template_scale=a.template_scale,
            map_size=a.map_size, qa=not a.no_qa, mc=mc,
            author_root=str(Path(a.author_root).resolve()) if Path(a.author_root).exists() else None,
        )
        write_dataset_meta(out, mc, cal, avatar, sizes, mask_stats, gauge, {
            "template_kind": maps_report.get("template_kind"),
            "template_is_clothed": maps_report.get("template_is_clothed"),
            "checks": maps_report.get("checks"),
            "report": "bridge_report.json",
        })

    rep = verify_dataset(out, mc=mc, require_maps=not a.no_maps)
    print(json.dumps({"ok": rep["ok"], "errors": rep["errors"][:20],
                      "warnings": rep["warnings"][:10],
                      "images": rep["checks"].get("images_read"),
                      "pos_maps": rep["checks"].get("pos_maps_read")}, indent=2))
    return 0 if rep["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
