def load_calibration(cal_path: Path, acceptance_path: Path, scale: float) -> Dict[str, Any]:
    if not cal_path.exists():
        raise FileNotFoundError(cal_path)
    if not acceptance_path.exists():
        raise FileNotFoundError(
            f"{acceptance_path} is required: calibration must come from the accepted candidate")
    acc = _read_json(acceptance_path)
    if not acc.get("accepted_for_static_fit", False):
        raise RuntimeError("acceptance.json does not mark the calibration accepted_for_static_fit")
    cand = acc.get("candidate")
    cand_path = (ROOT / cand.replace("\\", "/")).resolve() if cand else None
    if cand_path is None or cand_path.resolve() != cal_path.resolve():
        raise ValueError(f"calibration {cal_path} is not acceptance.json candidate {cand_path}")
    digest = sha256_file(cal_path)
    if digest != acc.get("candidate_sha256"):
        raise ValueError(f"calibration sha256 mismatch: {digest} != {acc.get('candidate_sha256')}")

    cal = np.load(cal_path, allow_pickle=True)
    K = np.asarray(cal["K"], np.float64)
    W = np.asarray(cal["W"], np.float64)
    cams = _as_cams(cal["cams"])
    if K.shape != (len(cams), 3, 3) or W.shape != (len(cams), 4, 4):
        raise ValueError(f"unexpected K/W shapes {K.shape}, {W.shape}, cams={len(cams)}")
    if len(cams) != 8:
        raise ValueError(f"expected 8 cameras, got {len(cams)}: {cams}")
    if not np.isfinite(K).all() or not np.isfinite(W).all():
        raise ValueError("K/W contain non-finite values")
    if not np.allclose(W[:, 3], np.array([0, 0, 0, 1], np.float32), atol=1e-6):
        raise ValueError("W bottom rows are not [0,0,0,1]")
    # camera0 identity is part of the accepted gauge; do not silently re-gauge.
    if not np.allclose(W[0], np.eye(4), atol=1e-5):
        raise ValueError("camera0 is not identity; accepted calibration contract says it is")
    # Every serial should appear in the acceptance check names.
    acc_text = json.dumps(acc.get("checks", {}))
    missing = [c for c in cams if c not in acc_text]
    if missing:
        raise ValueError(f"serials missing from acceptance checks: {missing}")

    W_model = W.copy()
    W_model[:, :3, 3] /= float(scale)
    return {"path": str(cal_path), "sha256": digest, "acceptance": str(acceptance_path),
            "K": K, "W_world": W, "W_model": W_model, "cams": cams, "scale": float(scale),
            "coordinate_convention": acc.get("coordinate_convention"),
            "scope": acc.get("scope"), "candidate": str(cand_path)}


def projection_gauge_check(cal: Dict[str, Any], scale: float, centers: np.ndarray) -> Dict[str, Any]:
    rng = np.random.default_rng(20261101)
    # Sample the observed person's region rather than the camera origin, whose
    # projection becomes arbitrarily ill-conditioned close to the focal plane.
    centers = np.asarray(centers, dtype=np.float64).reshape(-1, 3)
    Xm = centers[rng.integers(len(centers), size=5000)] + rng.normal(size=(5000, 3)) * 0.2
    Xw = Xm * float(scale)
    rows = []
    for i in range(len(cal["cams"])):
        uv_m, z_m = project(cal["K"][i], cal["W_model"][i], Xm)
        uv_w, z_w = project(cal["K"][i], cal["W_world"][i], Xw)
        ok = (z_m > 1e-4) & (z_w > 1e-4)
        d = np.linalg.norm(uv_m[ok] - uv_w[ok], axis=1) if ok.any() else np.array([np.nan])
        rows.append({"camera": cal["cams"][i], "n": int(ok.sum()),
                     "max_px": float(np.nanmax(d)), "median_px": float(np.nanmedian(d))})
    return {"scale": float(scale), "n_points": 5000, "per_camera": rows,
            "max_px": max(r["max_px"] for r in rows)}


