#!/usr/bin/env python
"""Adapt MJJ001's real 8-camera, 99-time capture to AnimatableGaussians input.

Output (all under cloth_dynamics/data/, never the project assets):

    data/mjj001_animatable/
      calibration.json                  author MvRgbDatasetTHuman4/ActorsHQ layout
      smpl_params.npz                   SMPL-X params in model units
      images/cam00..cam07/%08d.jpg      pose_idx order, source mapping recorded
      masks/cam00..cam07/%08d.jpg       existing MJJ SAM2 masks (no fallback)
      frame_list.txt                    pose indices 0..T-1 for author frame_range
      template.ply                      initial template (SMPL-X body, NOT clothed)
      smpl_pos_map/                     generated by template_bridge.py
      qa/                               projection/contact checks, not quality results
      dataset_meta.json, camera_contract.json, verify_report.json

Key coordinate decision
-----------------------
The project motion is in a world gauge where `world = scale * (SMPL-X model point
+ transl_model)`.  The author code expects SMPL-X model units.  Therefore:
    transl_model = translation_world / scale
    camera R_model = R_world (orthonormal, unchanged)
    camera T_model = T_world / scale
    K unchanged, image size unchanged
This is an exact similarity gauge: projected pixels are invariant.  No image
resize, crop, or aspect stretch is performed; if one were added, K would have to
be transformed in the same operation (not implemented, because the official
training path does its own patch crop).

Time decision
-------------
`pose_idx` is contiguous 0..T-1 in the author arrays.  The true source capture
indices are stored in `dataset_meta.json["source_frames"]` and used to select the
original images.  The historical 100-index seek with the duplicated 66/67 frame
is never used: extract_motion() validates uniqueness and length 99.

Run (CPU only):
    python prepare_inputs.py --dry-run
    python prepare_inputs.py
    python prepare_inputs.py --verify-only

No GPU, no package install, no model download, no writes outside data/.
"""

