def verify_dataset(out: Path, mc: Optional[MotionContract] = None,
                   require_maps: bool = True) -> Dict[str, Any]:
    errors: List[str] = []
    warnings: List[str] = []
    checks: Dict[str, Any] = {}
    try:
        cal = _read_json(out / "calibration.json")
        names = sorted(cal.keys())
        if len(names) != 8 or names != [f"cam{i:02d}" for i in range(8)]:
            errors.append(f"calibration camera keys are not cam00..cam07: {names}")
        for n in names:
            c = cal[n]
            if not all(k in c for k in ("R", "T", "K", "imgSize")):
                errors.append(f"{n} missing R/T/K/imgSize")
        checks["calibration_cameras"] = names
        checks["frame_list"] = (out / "frame_list.txt").exists()
        checks["missing_img_files"] = (out / "missing_img_files.txt").exists()
        if not checks["frame_list"]:
            errors.append("missing frame_list.txt (official frame_range filename)")
        if not checks["missing_img_files"]:
            errors.append("missing missing_img_files.txt (MvRgbDatasetTHuman4 opens it in training mode)")
    except Exception as e:
        errors.append(f"calibration: {e!r}")
        cal = {}

    try:
        sp = np.load(out / "smpl_params.npz", allow_pickle=True)
        keys = set(sp.keys())
        need = {"betas", "global_orient", "transl", "body_pose", "jaw_pose",
                "expression", "left_hand_pose", "right_hand_pose"}
        if not need <= keys:
            errors.append(f"smpl_params missing {sorted(need - keys)}")
        T = int(sp["body_pose"].shape[0]) if "body_pose" in keys else 0
        checks["smpl_params"] = {k: list(sp[k].shape) for k in sorted(keys)}
        for k, dim in (("global_orient", 3), ("transl", 3), ("body_pose", 63),
                       ("jaw_pose", 3),
                       ("left_hand_pose", 45), ("right_hand_pose", 45)):
            if k in keys and (sp[k].ndim != 2 or sp[k].shape[0] != T or sp[k].shape[1] != dim):
                errors.append(f"{k} shape {sp[k].shape} != ({T},{dim})")
        if "expression" in keys:
            if sp["expression"].ndim != 2 or sp["expression"].shape[0] != T:
                errors.append(f"expression shape {sp['expression'].shape} has wrong T")
            else:
                checks["expression_dim"] = int(sp["expression"].shape[1])
                if checks["expression_dim"] != 10:
                    warnings.append(
                        f"expression_dim={checks['expression_dim']}; the author reader must be "
                        f"initialized with num_expression_coeffs={checks['expression_dim']} "
                        "(minimal vendored-SMPLX patch), not truncated to 10"
                    )
        if "betas" in keys and sp["betas"].shape != (1, 10):
            errors.append(f"betas shape {sp['betas'].shape} != (1,10)")
        checks["T"] = T
    except Exception as e:
        errors.append(f"smpl_params: {e!r}")
        T = 0

    if mc is not None and T and mc.T != T:
        errors.append(f"motion T={mc.T} != smpl_params T={T}")

    img_ok = 0
    mask_ok = 0
    map_ok = 0
    binary = True
    sizes = {}
    for ci in range(8):
        sizes[ci] = set()
    try:
        for t in range(T):
            for ci in range(8):
                ip = out / "images" / f"cam{ci:02d}" / f"{t:08d}.jpg"
                mp = out / "masks" / f"cam{ci:02d}" / f"{t:08d}.jpg"
                im = read_image(str(ip), cv.IMREAD_COLOR)
                ma = read_image(str(mp), cv.IMREAD_GRAYSCALE)
                if im is None:
                    errors.append(f"missing/unreadable image {ip}")
                else:
                    img_ok += 1
                    sizes[ci].add((im.shape[1], im.shape[0]))
                if ma is None:
                    errors.append(f"missing/unreadable mask {mp}")
                else:
                    mask_ok += 1
                    # JPEG masks are lossy at edges; the author thresholds >128.
                    # Require meaningful foreground and background, not exact 0/255.
                    fg = int(np.count_nonzero(ma > 128))
                    bg = int(np.count_nonzero(ma <= 128))
                    if fg == 0:
                        warnings.append(f"empty mask {mp}")
                    if bg == 0:
                        warnings.append(f"all-foreground mask {mp}")
                    if not (fg and bg):
                        binary = False
                if require_maps:
                    pm = out / "smpl_pos_map" / f"{t:08d}.exr"
                    arr = read_image(str(pm), cv.IMREAD_UNCHANGED) if pm.exists() else None
                    if arr is None:
                        errors.append(f"missing/unreadable pos map {pm}")
                    else:
                        map_ok += 1
                        if arr.shape != (512, 1024, 3):
                            errors.append(f"pos map shape {arr.shape} != (512,1024,3): {pm}")
                        if not np.isfinite(arr).all():
                            errors.append(f"non-finite pos map {pm}")
        for ci, s in sizes.items():
            if len(s) > 1:
                errors.append(f"camera {ci} images have inconsistent sizes {sorted(s)}")
        checks["images_read"] = img_ok
        checks["masks_read"] = mask_ok
        checks["masks_nonempty"] = binary
        checks["pos_maps_read"] = map_ok
        checks["image_sizes"] = {f"cam{i:02d}": sorted(list(s)) for i, s in sizes.items()}
    except Exception as e:
        errors.append(f"image/mask/map loop: {e!r}")

    if require_maps:
        try:
            cano = read_image(str(out / "smpl_pos_map/cano_smpl_pos_map.exr"), cv.IMREAD_UNCHANGED)
            if cano is None:
                errors.append("missing cano_smpl_pos_map.exr")
            elif cano.shape != (1024, 2048, 3):
                errors.append(f"cano pos map shape {cano.shape} != (1024,2048,3)")
            lbs = np.load(out / "smpl_pos_map/init_pts_lbs.npy")
            if lbs.ndim != 2 or lbs.shape[1] != 55:
                errors.append(f"init_pts_lbs shape {lbs.shape} != (N,55)")
            else:
                rs = lbs.sum(1)
                checks["init_pts_lbs"] = {"shape": list(lbs.shape),
                                          "row_sum_min": float(rs.min()),
                                          "row_sum_max": float(rs.max())}
                if abs(float(rs.mean()) - 1.0) > 1e-3:
                    errors.append(f"init_pts_lbs rows do not sum to 1 (mean {rs.mean():.6f})")
        except Exception as e:
            errors.append(f"canonical map/lbs: {e!r}")

    # Mimic the official reader's calibration construction and boundary mask.
    try:
        import cv2
        for n in sorted(cal.keys()):
            c = cal[n]
            extr = np.eye(4, dtype=np.float32)
            extr[:3, :3] = np.array(c["R"], np.float32).reshape(3, 3)
            extr[:3, 3] = np.array(c["T"], np.float32).reshape(3)
            intr = np.array(c["K"], np.float32).reshape(3, 3)
            if not np.isfinite(extr).all() or not np.isfinite(intr).all():
                errors.append(f"{n} non-finite extr/intr")
        m = read_image(str(out / "masks/cam00/00000000.jpg"), cv.IMREAD_GRAYSCALE)
        if m is not None:
            kernel = np.ones((5, 5), np.uint8)
            mm = np.where(m > 128, 1, 0).astype(np.uint8)
            er = cv.erode(mm, kernel)
            di = cv.dilate(mm, kernel)
            boundary = (di - er) == 1
            checks["boundary_mask_fraction"] = float(boundary.mean())
    except Exception as e:
        warnings.append(f"reader-mimic check: {e!r}")

    report = {"ok": not errors, "errors": errors, "warnings": warnings, "checks": checks,
              "scope": "input layout/reader contract only; NOT a reconstruction quality result"}
    write_json(out / "verify_report.json", report)
    return report


