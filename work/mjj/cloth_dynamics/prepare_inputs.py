def write_calibration_json(out: Path, cal: Dict[str, Any], sizes: List[List[int]]) -> None:
    data: Dict[str, Any] = {}
    for i, serial in enumerate(cal["cams"]):
        W = cal["W_model"][i]
        data[f"cam{i:02d}"] = {
            "R": W[:3, :3].astype(float).tolist(),
            "T": W[:3, 3].astype(float).tolist(),
            "K": cal["K"][i].astype(float).tolist(),
            "imgSize": [int(sizes[i][0]), int(sizes[i][1])],
             # extra fields are ignored by the official loader; kept for audit
            "_serial": serial,
            "_source_T_world": cal["W_world"][i, :3, 3].astype(float).tolist(),
        }
    # Do not leave our underscore keys in the file the author reads: the
    # official loader only reads R/T/K/imgSize, but a strict manifest check
    # should see exactly the contract.  Separate provenance is below.
    for k in list(data.keys()):
        data[k] = {kk: vv for kk, vv in data[k].items() if not kk.startswith("_")}
    (out / "calibration.json").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


