def _read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _as_cams(raw: Any) -> List[str]:
    out = []
    for x in np.asarray(raw).reshape(-1):
        if isinstance(x, bytes):
            x = x.decode("utf-8")
        out.append(str(x))
    return out


def project(K: np.ndarray, W: np.ndarray, X: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    pc = X @ W[:3, :3].T + W[:3, 3]
    uv = (K @ pc.T).T
    return uv[:, :2] / np.clip(uv[:, 2:], 1e-8, None), pc[:, 2]


def summarize(obj: Any, depth: int = 0) -> Any:
    if depth > 2:
        return type(obj).__name__
    if isinstance(obj, torch.Tensor):
        return {"tensor_shape": list(obj.shape), "dtype": str(obj.dtype)}
    if isinstance(obj, np.ndarray):
        return {"array_shape": list(obj.shape), "dtype": str(obj.dtype)}
    if isinstance(obj, dict):
        return {str(k): summarize(v, depth + 1) for k, v in list(obj.items())[:40]}
    if isinstance(obj, (list, tuple)):
        return {"sequence_len": len(obj), "first": summarize(obj[0], depth + 1) if obj else None}
    return type(obj).__name__


def audit_avatar(path: Path) -> Dict[str, Any]:
    out: Dict[str, Any] = {"path": str(path), "exists": path.exists()}
    if not path.exists():
        out["error"] = "missing"
        return out
    out["sha256"] = sha256_file(path)
    out["bytes"] = path.stat().st_size
    try:
        try:
            obj = torch.load(path, map_location="cpu", weights_only=True)
        except Exception:
            obj = torch.load(path, map_location="cpu", weights_only=False)
            out["weights_only_fallback"] = True
        out["top_level"] = summarize(obj)
        if isinstance(obj, dict):
            out["keys"] = list(map(str, obj.keys()))
            if "features" in obj and isinstance(obj["features"], torch.Tensor):
                out["feature_dim"] = int(obj["features"].shape[-1])
            if "rig" in obj and isinstance(obj["rig"], dict):
                out["rig_keys"] = list(map(str, obj["rig"].keys()))
                if "rest_joints" in obj["rig"] and isinstance(obj["rig"]["rest_joints"], torch.Tensor):
                    out["rig_joint_count"] = int(obj["rig"]["rest_joints"].shape[0])
        out["used_for_template"] = False
        out["reason_not_used"] = ("avatar.pt is a Gaussian/rig bundle, not a clothing mesh; "
                                  "it cannot be passed as the author's template.ply. "
                                  "Only re-used later for face/hand/identity diagnostics.")
    except Exception as e:
        out["load_error"] = repr(e)
    return out


